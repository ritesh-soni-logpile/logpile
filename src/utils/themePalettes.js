export function themeVars(layoutKey = 'cinematic', colorPaletteKey = 'auto') {
  const p = LAYOUT_PALETTES[layoutKey] || getAddonPalette(layoutKey) || LAYOUT_PALETTES.cinematic
  const cp = colorPaletteKey && colorPaletteKey !== 'auto' ? COLOR_PALETTES[colorPaletteKey] : null

  const accent = cp?.accent || p.accent
  const accentGlow = cp?.accentGlow || p.accentGlow
  const accentContrast = cp?.accentContrast || p.accentContrast
  const borderHover = cp?.borderHover || p.borderHover
  const badgeBg = cp?.badgeBg || p.badgeBg
  const badgeText = cp?.badgeText || p.badgeText

  return {
    '--bg-base': p.base,
    '--bg-primary': p.base,
    '--bg-app': p.base,
    '--bg-surface': p.surface,
    '--bg-surface-hover': p.surfaceHover,
    '--bg-card': p.card || p.surface,
    '--text-primary': p.textPrimary,
    '--text-secondary': p.textSecondary,
    '--text-muted': p.textMuted,
    '--text-highlight': accent,
    '--accent': accent,
    '--accent-color': accent,
    '--accent-glow': accentGlow,
    '--accent-contrast': accentContrast,
    '--border-color': p.borderColor,
    '--border-hover': borderHover,
    '--badge-bg': badgeBg,
    '--badge-text': badgeText,
  }
}
